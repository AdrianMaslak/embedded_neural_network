#!/usr/bin/env python3
"""
Train ShapeCNN on the shape dataset and export it for Vitis HLS.

    in 60x80x1
    B1  Conv3x3( 1-> 8)+BN+ReLU+MaxPool2  -> 30x40x8
    B2  Conv3x3( 8->16)+BN+ReLU+MaxPool2  -> 15x20x16
    B3  Conv3x3(16->16)+BN+ReLU+MaxPool2  ->  7x10x16
    B4  Conv3x3(16->32)+BN+ReLU           ->  7x10x32
    GAP -> Dense(32->4) -> softmax (training only; HLS returns argmax of logits)

(The lecture-7 depthwise CNN, receptive field ~8 px, stayed at ~32 % on
rotated/scaled shapes; this network has a ~38 px receptive field.)

Outputs:
    cnn/out/models/shape_cnn.keras
    cnn/out/plots/   loss/acc curves, confusion matrices
    cnn/out/reports/ metrics.json, classification_report_test.txt
    hls/cnn/cnn_weights.h          BN-folded weights as C arrays
    hls/cnn/cnn_test_vectors.txt   test images + label + Keras prediction
"""
import json
import os
import random
import sys
from pathlib import Path

os.environ["CUDA_VISIBLE_DEVICES"] = "-1"
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "2"
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import tensorflow as tf
from sklearn.metrics import ConfusionMatrixDisplay, classification_report, confusion_matrix
from tensorflow.keras import layers, models
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau

from common import CLASSES, IMG_H, IMG_W, ROOT, cnn_normalize, list_split, load_gray

SEED = 42
EPOCHS = 60
BATCH = 32
LR = 2e-3
CH = [8, 16, 16, 32]           # conv output channels B1..B4

OUT = ROOT / "cnn" / "out"
HLS_DIR = ROOT / "hls" / "cnn"

random.seed(SEED)
np.random.seed(SEED)
tf.random.set_seed(SEED)


def load(split):
    items = list_split(split)
    raw = np.stack([load_gray(p) for p, _ in items])
    y = np.array([l for _, l in items], dtype=np.int64)
    return raw, cnn_normalize(raw)[..., None], y


def build_model(n_classes):
    bn = dict(momentum=0.9, epsilon=1e-3)
    seq = [layers.Input((IMG_H, IMG_W, 1))]
    for i, c in enumerate(CH):
        seq += [layers.Conv2D(c, 3, padding="same", use_bias=False, name=f"conv{i + 1}"),
                layers.BatchNormalization(name=f"bn{i + 1}", **bn),
                layers.ReLU(name=f"relu{i + 1}")]
        if i < 3:
            seq.append(layers.MaxPooling2D(2, name=f"pool{i + 1}"))
    seq += [layers.GlobalAveragePooling2D(name="gap"),
            layers.Dense(n_classes, name="fc"),
            layers.Softmax(name="softmax")]
    return models.Sequential(seq)


# ---------------- BN folding + C export ----------------
def c_array(a):
    if a.ndim == 1:
        return "{" + ", ".join(f"{float(v):.8g}" for v in a) + "}"
    return "{" + ",\n ".join(c_array(r) for r in a) + "}"


def export_header(model, path):
    """conv weights as W[co][ci][kh*3+kw] (BN folded), bias[co]; fc W[o][i]."""
    out = ["// Auto-generated by cnn/train_cnn.py - BN-folded ShapeCNN weights", "#pragma once", ""]
    ranges = {}
    for i in range(1, 5):
        W = model.get_layer(f"conv{i}").get_weights()[0]          # (3,3,ci,co)
        bnl = model.get_layer(f"bn{i}")
        g, b, m, v = bnl.get_weights()
        s = g / np.sqrt(v + bnl.epsilon)
        Wf = np.transpose(W * s, (3, 2, 0, 1)).reshape(W.shape[3], W.shape[2], 9)
        bf = b - m * s
        out.append(f"static const wt_t C{i}_W[{Wf.shape[0]}][{Wf.shape[1]}][9] = {c_array(Wf)};")
        out.append(f"static const wt_t C{i}_B[{bf.size}] = {c_array(bf)};\n")
        ranges[f"conv{i}"] = [float(min(Wf.min(), bf.min())), float(max(Wf.max(), bf.max()))]
    Wd, bd = model.get_layer("fc").get_weights()                   # (32,4)
    out.append(f"static const wt_t FC_W[{Wd.shape[1]}][{Wd.shape[0]}] = {c_array(Wd.T)};")
    out.append(f"static const wt_t FC_B[{bd.size}] = {c_array(bd)};")
    ranges["fc"] = [float(min(Wd.min(), bd.min())), float(max(Wd.max(), bd.max()))]
    path.write_text("\n".join(out) + "\n")
    return ranges


def activation_ranges(model, x):
    names = [f"relu{i}" for i in range(1, 5)] + ["gap", "fc"]
    probe = models.Model(model.inputs, [model.get_layer(n).output for n in names])
    return {n: float(np.abs(a).max()) for n, a in zip(names, probe.predict(x, verbose=0))}


def plot_cm(y, p, path, title):
    fig, ax = plt.subplots(figsize=(5, 4.5))
    ConfusionMatrixDisplay(confusion_matrix(y, p, labels=range(len(CLASSES))),
                           display_labels=CLASSES).plot(ax=ax, cmap="Blues", colorbar=False)
    ax.set_title(title)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main():
    for d in ("models", "plots", "reports"):
        (OUT / d).mkdir(parents=True, exist_ok=True)
    HLS_DIR.mkdir(parents=True, exist_ok=True)

    _, x_tr, y_tr = load("train")
    _, x_va, y_va = load("val")
    raw_te, x_te, y_te = load("test")
    print(f"train {len(y_tr)}  val {len(y_va)}  test {len(y_te)}")

    model = build_model(len(CLASSES))
    model.compile(optimizer=tf.keras.optimizers.Adam(LR),
                  loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    model.summary()
    hist = model.fit(
        x_tr, y_tr, validation_data=(x_va, y_va), epochs=EPOCHS, batch_size=BATCH,
        callbacks=[EarlyStopping("val_loss", patience=10, restore_best_weights=True),
                   ReduceLROnPlateau("val_loss", factor=0.5, patience=3, min_lr=1e-5)],
        verbose=2)

    h = hist.history
    for key in ("loss", "accuracy"):
        fig = plt.figure(figsize=(5, 3.5))
        plt.plot(h[key], label="train"); plt.plot(h["val_" + key], label="val")
        plt.xlabel("epoch"); plt.ylabel(key); plt.grid(True); plt.legend(); plt.tight_layout()
        fig.savefig(OUT / "plots" / f"cnn_{key}.png", dpi=150)
        plt.close(fig)

    p_va = model.predict(x_va, verbose=0).argmax(1)
    p_te = model.predict(x_te, verbose=0).argmax(1)
    plot_cm(y_va, p_va, OUT / "plots" / "cnn_cm_val.png", "CNN (Keras) - validation")
    plot_cm(y_te, p_te, OUT / "plots" / "cnn_cm_test.png", "CNN (Keras) - test")
    rep = classification_report(y_te, p_te, target_names=CLASSES, digits=4)
    print(rep)
    (OUT / "reports" / "classification_report_test.txt").write_text(rep)

    cm = confusion_matrix(y_te, p_te)
    metrics = {
        "val_acc": float((p_va == y_va).mean()),
        "test_acc": float((p_te == y_te).mean()),
        "test_per_class_acc": {c: float(cm[i, i] / cm[i].sum()) for i, c in enumerate(CLASSES)},
        "epochs_run": len(h["loss"]),
        "params": int(model.count_params()),
        "activation_absmax_test": activation_ranges(model, x_te),
    }
    model.save(OUT / "models" / "shape_cnn.keras")
    metrics["folded_weight_range"] = export_header(model, HLS_DIR / "cnn_weights.h")
    (OUT / "reports" / "metrics.json").write_text(json.dumps(metrics, indent=2))
    print(json.dumps(metrics, indent=2))

    with open(HLS_DIR / "cnn_test_vectors.txt", "w") as f:
        f.write(f"{len(y_te)}\n")
        for img, y, p in zip(raw_te, y_te, p_te):
            f.write(f"{y} {p} " + " ".join(map(str, img.reshape(-1))) + "\n")
    np.save(OUT / "reports" / "keras_test_pred.npy", p_te)
    print("done ->", OUT)


if __name__ == "__main__":
    main()
